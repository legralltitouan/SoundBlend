/* Connexion et déconnexion simulées sans recharger : l'avatar garde ses hooks
   et les exclusions locales restent disponibles. Aucun compte réel. */
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const base = process.env.SOUNDBLEND_URL || process.env.SOUNDBLEND_DEV_URL || 'http://localhost:5173/';
const browser = await chromium.launch({ ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}), args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, serviceWorkers: 'block' });
const headers = { 'content-type': 'application/json', 'access-control-allow-origin': '*' };
await ctx.addInitScript(() => { localStorage.setItem('soundblend_onboarded', '1'); });
await ctx.route('https://accounts.google.com/**', r => r.fulfill({ status: 200, contentType: 'application/javascript', body: `window.google={accounts:{oauth2:{initTokenClient:(o)=>({requestAccessToken:()=>setTimeout(()=>o.callback({access_token:'simule',expires_in:3600}),10)}),revoke:(_t,cb)=>cb()}}};` }));
await ctx.route('https://www.googleapis.com/oauth2/**', r => r.fulfill({ status: 200, headers, body: JSON.stringify({ name: 'Alex Test', email: 'test@example.test', picture: 'https://example.test/avatar.png' }) }));
await ctx.route('https://www.googleapis.com/youtube/v3/**', r => r.fulfill({ status: 200, headers, body: '{"items":[]}' }));
await ctx.route(/https:\/\/www\.googleapis\.com\/(drive|upload\/drive)\//, r => {
  const u = new URL(r.request().url());
  if (u.pathname.includes('/upload/')) return r.fulfill({ status: 200, headers, body: '{"id":"f1"}' });
  if (u.searchParams.get('alt') === 'media') return r.fulfill({ status: 200, headers, body: '{"schema":2,"exclusions":[],"blends":[],"decouvertes":[],"suppressionsBlends":{}}' });
  return r.fulfill({ status: 200, headers, body: '{"files":[]}' });
});
await ctx.route(/pipedapi\.|api\.piped\./, r => r.fulfill({ status: 200, headers, body: JSON.stringify({ items: [{ type: 'channel', name: 'Artiste test', url: '/channel/test' }] }) }));
const p = await ctx.newPage(); const errors = []; p.on('pageerror', e => errors.push(e.message));
let n = 0; const check = (v, text) => { assert.ok(v, text); n++; console.log('  ✓ ' + text); };
await p.goto(base, { waitUntil: 'domcontentloaded' }); await p.waitForSelector('.ytm-shell');
await p.locator('.ytm-mobile-bar [aria-label="Réglages du compte"]').click();
await p.getByRole('button', { name: 'Connecter mon compte', exact: true }).click();
await p.getByRole('button', { name: 'Se déconnecter' }).waitFor();
check(await p.locator('.ytm-mobile-bar [aria-label="Réglages du compte"]').getAttribute('title') === 'Alex Test', 'avatar mis à jour après connexion sans rechargement');
await p.getByRole('button', { name: 'Ajouter une exclusion' }).click();
await p.getByRole('tab', { name: /Artistes/ }).click();
await p.getByRole('searchbox', { name: 'Rechercher dans les exclusions et le catalogue' }).fill('Artiste test');
await p.getByRole('button', { name: 'Exclure Artiste test' }).click();
await p.keyboard.press('Escape');
await p.getByRole('button', { name: 'Se déconnecter' }).click();
await p.getByRole('button', { name: 'Connecter mon compte', exact: true }).waitFor();
check(await p.locator('.ytm-mobile-bar [aria-label="Réglages du compte"]').getAttribute('title') === 'Réglages et connexion', 'avatar remis à l’état déconnecté sans rechargement');
await p.getByRole('button', { name: 'Afficher la liste des exclusions' }).click();
await p.getByRole('tab', { name: /Artistes/ }).click();
check(await p.getByRole('button', { name: 'Débloquer Artiste test' }).isVisible(), 'exclusion locale conservée après déconnexion');
await p.keyboard.press('Escape');
await p.getByRole('button', { name: 'Connecter mon compte', exact: true }).click();
await p.getByRole('button', { name: 'Se déconnecter' }).waitFor();
check(errors.length === 0, `reconnexion sans exception JavaScript (${errors.join('; ')})`);
console.log(`\n${n}/${n} contrôles connexion/avatar réussis (services simulés).`);
await browser.close();
